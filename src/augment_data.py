def infer_question_type_from_text(text: str) -> str:
    """从题目文本推断题型"""
    option_pattern = re.compile(r"[\s\n\r]+[A-F][、.．:]")
    fill_pattern = re.compile(r"填空|____|＿")
    prove_pattern = re.compile(r"证明|求证")

    if option_pattern.search(text):
        return "选择题"
    if fill_pattern.search(text):
        return "解答题"
    if prove_pattern.search(text):
        return "解答题"
    if "判断" in text:
        return "判断题"
    if any(kw in text for kw in ["计算", "求", "化简", "解方程", "写出", "完成"]):
        return "解答题"
    return "选择题"  # 默认


def generate_samples_for_knowledge(kp: str, target_count: int, rng: random.Random) -> list:
    """为指定知识点生成目标数量的样本（带多重文本扰动）"""
    if kp not in KNOWLEDGE_TEMPLATES:
        return []

    template = KNOWLEDGE_TEMPLATES[kp]
    keywords = template["keywords"]
    templates = template["templates"]

    samples = []
    used_texts = set()
    subject = kp.split("::")[0]

    # 提高尝试倍数，因为扰动会增加多样性
    for _ in range(target_count * 5):
        if len(samples) >= target_count:
            break
        tpl = rng.choice(templates)
        # 为每个 {kw} 随机填入关键词
        def _replace_one(match):
            return rng.choice(keywords)
        # 替换模板中所有 {kw}，每个位置随机选一个关键词
        while "{kw}" in tpl:
            tpl = tpl.replace("{kw}", rng.choice(keywords), 1)

        text = perturb_text(tpl, rng)
        text = text.strip()
        if len(text) < 6:
            continue
        if text in used_texts:
            continue
        used_texts.add(text)

        q_type = infer_question_type_from_text(text)
        samples.append({
            "text": text,
            "subject": subject,
            "question_type": q_type,
            "raw_question_type": "客观题" if q_type in ("选择题", "判断题") else "主观题",
            "knowledge_point": kp,
            "answer": "",
        })

    return samples


def main():
    write_log("augment", "数据增强 V2 开始...")

    # 读取现有数据
    train_df = pd.read_csv(os.path.join(PROC_DIR, "train.csv"))
    val_df = pd.read_csv(os.path.join(PROC_DIR, "val.csv"))
    test_df = pd.read_csv(os.path.join(PROC_DIR, "test.csv"))

    all_df = pd.concat([train_df, val_df, test_df], ignore_index=True)
    write_log("augment", f"原始数据：训练 {len(train_df)} / 验证 {len(val_df)} / 测试 {len(test_df)}，总计 {len(all_df)}")

    kp_counts = Counter(all_df["knowledge_point"].tolist())
    write_log("augment", f"知识点类别数：{len(kp_counts)}")

    with open(os.path.join(PROC_DIR, "labels.json"), encoding="utf-8") as f:
        labels = json.load(f)

    rng = random.Random(RANDOM_SEED)

    augmented = []
    for kp, count in kp_counts.items():
        if count < TARGET_MIN:
            need = TARGET_MIN - count
            new_samples = generate_samples_for_knowledge(kp, need, rng)
            if new_samples:
                augmented.extend(new_samples)
                write_log("augment", f"  {kp}: 原有 {count} 条，生成 {len(new_samples)} 条新样本")
            else:
                write_log("augment", f"  {kp}: 原有 {count} 条，无模板可用，跳过", "WARN")

    write_log("augment", f"共生成 {len(augmented)} 条增强样本")

    if not augmented:
        write_log("augment", "无增强样本生成，退出", "WARN")
        return

    combined = all_df.to_dict("records") + augmented
    seen = set()
    deduped = []
    for s in combined:
        key = s["text"]
        if key in seen:
            continue
        seen.add(key)
        deduped.append(s)
    write_log("augment", f"合并去重后：{len(deduped)} 条")

    # 分层划分
    by_subject = defaultdict(list)
    for s in deduped:
        by_subject[s["subject"]].append(s)

    train, val, test = [], [], []
    for subj, group in by_subject.items():
        rng.shuffle(group)
        n = len(group)
        n_train = int(n * 0.70)
        n_val = int(n * 0.15)
        train.extend(group[:n_train])
        val.extend(group[n_train:n_train + n_val])
        test.extend(group[n_train + n_val:])

    rng.shuffle(train)
    rng.shuffle(val)
    rng.shuffle(test)

    write_log("augment", f"重新划分：训练 {len(train)} / 验证 {len(val)} / 测试 {len(test)}")

    import csv
    def write_csv(path, samples):
        with open(path, "w", encoding="utf-8-sig", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=["text", "subject", "question_type", "knowledge_point", "raw_question_type", "answer"])
            writer.writeheader()
            for s in samples:
                writer.writerow(s)

    write_csv(os.path.join(PROC_DIR, "train.csv"), train)
    write_csv(os.path.join(PROC_DIR, "val.csv"), val)
    write_csv(os.path.join(PROC_DIR, "test.csv"), test)

    labels["stats"]["n_samples"] = len(deduped)
    labels["stats"]["n_train"] = len(train)
    labels["stats"]["n_val"] = len(val)
    labels["stats"]["n_test"] = len(test)
    labels["stats"]["per_subject"] = dict(Counter(s["subject"] for s in deduped))
    labels["stats"]["per_type"] = dict(Counter(s["question_type"] for s in deduped))
    labels["stats"]["per_knowledge"] = dict(Counter(s["knowledge_point"] for s in deduped))

    with open(os.path.join(PROC_DIR, "labels.json"), "w", encoding="utf-8") as f:
        json.dump(labels, f, ensure_ascii=False, indent=2)

    write_log("augment", "=" * 50)
    write_log("augment", "增强后各知识点样本数：")
    new_counts = Counter(s["knowledge_point"] for s in deduped)
    for kp in sorted(new_counts.keys()):
        old = kp_counts.get(kp, 0)
        new = new_counts[kp]
        marker = " ← 新增" if old == 0 else (f" ← +{new - old}" if new > old else "")
        write_log("augment", f"  {kp}: {old} → {new}{marker}")
    write_log("augment", "=" * 50)
    write_log("augment", f"数据增强 V2 完成！总样本数 {len(deduped)} 条")


if __name__ == "__main__":
    main()
