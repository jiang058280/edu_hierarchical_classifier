_OPT_LETTERS = list("ABCDEFGH")


def _swap_option_letters(text: str, rng: random.Random) -> str:
    """将选项字母随机打乱（不改变语义，但增加多样性）"""
    # 匹配形如 "A. XXX B. XXX C. XXX D. XXX" 的选项
    m = re.findall(r"([A-G])[、.．:：]\s*([^A-G]{1,80}?)(?=\s*[A-G][、.．:：]|$)", text)
    if len(m) < 3:
        return text
    opts = [(letter, content.strip()) for letter, content in m]
    rng.shuffle(opts)
    # 重新按 A, B, C, D 分配
    new_parts = []
    for i, (_, content) in enumerate(opts):
        if i < len(_OPT_LETTERS):
            new_parts.append(f"{_OPT_LETTERS[i]}. {content}")
    old_match_pattern = r"\s*[A-G][、.．:：]\s*[^A-G]{1,80}?(\s*[A-G][、.．:：]|$)"
    # 简化处理：在最后把选项按顺序拼出来
    # 替换掉原来的全部选项块
    original_opts_block = ""
    # 找到"（ ）"或"?"之后出现的第一个选项串
    marker_idx = -1
    for marker in ["（ ）", "()", "？", "?"]:
        i = text.find(marker)
        if i > 0:
            marker_idx = i + len(marker)
            break
    if marker_idx < 0:
        return text
    before = text[:marker_idx]
    after = text[marker_idx:]
    # 把 after 中的选项替换为打乱后的
    new_opts = "  ".join(new_parts)
    # 尝试去掉 old options（匹配 A.xxx B.xxx ...）
    cleaned = re.sub(r"^\s*([A-G][、.．:：]\s*.+?){2,8}$", new_opts, after, count=1)
    if cleaned == after:
        # 正则没命中，在末尾追加新选项（简单兜底）
        return before + after + "  " + new_opts
    return before + cleaned


def _typo_insert(text: str, rng: random.Random) -> str:
    """极轻度"拼写/标点扰动"：增加数据鲁棒性，不影响语义"""
    ops = []
    # 全角→半角互换
    if rng.random() < 0.15:
        text = text.replace("（", "(").replace("）", ")").replace("：", ": ").replace("，", ", ")
    if rng.random() < 0.15:
        text = text.replace("A.", "A、").replace("B.", "B、").replace("C.", "C、").replace("D.", "D、")
    if rng.random() < 0.1:
        text = text.replace("  ", " ")
    if rng.random() < 0.08:
        # 随机在标点后加换行
        text = text.replace("。", "。\n", 1)
    return text


def perturb_text(text: str, rng: random.Random) -> str:
    """对题目文本做多种可组合的轻量扰动"""
    prefix = rng.choice(_PREFIXES)
    suffix = rng.choice(_SUFFIXES)
    text = prefix + text + suffix
    if rng.random() < 0.25:
        text = _swap_option_letters(text, rng)
    text = _typo_insert(text, rng)
    return text


